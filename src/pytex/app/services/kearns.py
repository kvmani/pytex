def _specimen_frame() -> Any:
    from pytex.core import FrameDomain, Handedness, ReferenceFrame

    return ReferenceFrame(
        name="specimen",
        domain=FrameDomain.SPECIMEN,
        axes=_SPECIMEN_AXES,
        handedness=Handedness.RIGHT,
    )


def _basal_pole(phase: Any) -> Any:
    """The ``(0002)`` plane of a hexagonal phase, refused for anything else.

    Refused rather than silently generalized: the machinery answers the question
    for any pole, but the *Kearns parameter* is defined on the basal pole of a
    hexagonal crystal, and a number computed from ``(002)`` of a cubic phase
    would be a valid second moment carrying an invalid name.
    """

    from pytex.core.hexagonal import is_hexagonal_phase
    from pytex.core.lattice import CrystalPlane

    if not is_hexagonal_phase(phase):
        raise InvalidInputError(
            f"The Kearns parameter is defined for hexagonal phases; {phase.name} is not one.",
            field="phase",
            hint=(
                "Choose a hexagonal phase — alpha-Zr, alpha-Ti, or Mg are in the catalogue. The "
                "parameter resolves the basal (0002) pole, which a cubic phase does not have."
            ),
        )
    return CrystalPlane.from_miller_bravais((0, 0, 0, 2), phase=phase)


def _data_lines(text: str, *, field: str) -> list[tuple[int, list[str]]]:
    """Split a pasted block into numbered, comment-free, tokenized rows.

    Comments after ``#`` and blank lines are dropped, and the original line
    number travels with each row so an error can name the line the user is
    looking at rather than the index of a filtered list.
    """

    rows: list[tuple[int, list[str]]] = []
    for number, raw in enumerate(str(text or "").splitlines(), start=1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        rows.append((number, line.replace(",", " ").split()))
    if not rows:
        raise InvalidInputError(
            "No data rows were given.",
            field=field,
            hint="Every line was blank or a comment. One measurement per line.",
        )
    return rows


def _number(token: str, *, line: int, field: str, what: str) -> float:
    try:
        value = float(token)
    except ValueError as error:
        raise InvalidInputError(
            f"Line {line}: '{token}' is not a number, and {what} must be.",
            field=field,
        ) from error
    if not math.isfinite(value):
        raise InvalidInputError(f"Line {line}: {what} must be finite.", field=field)
    return value


def _parse_reflections(text: str, *, phase: Any) -> list[Any]:
    """Parse the reflection block into `DiffractogramReflection` objects.

    Each line is ``h k i l  intensity  [random intensity]``. The four-index
    Miller-Bravais form is required rather than three-index, because the whole
    method turns on each reflection's tilt to ``[0001]`` and the four-index form
    is how that plane is named in every table the intensities will be read
    against.
    """

    from pytex.core.lattice import CrystalPlane
    from pytex.texture.kearns import DiffractogramReflection

    reflections: list[Any] = []
    for line, tokens in _data_lines(text, field="reflections"):
        if len(tokens) not in (5, 6):
            raise InvalidInputError(
                f"Line {line} has {len(tokens)} values; a reflection needs 5 or 6.",
                field="reflections",
                hint=(
                    "Write the plane as four Miller-Bravais indices, then the measured "
                    "intensity, then the random-powder intensity: `1 0 -1 3  2.292  1.0`."
                ),
            )
        indices = []
        for token in tokens[:4]:
            try:
                indices.append(int(token))
            except ValueError as error:
                raise InvalidInputError(
                    f"Line {line}: '{token}' is not a whole number, and a Miller-Bravais "
                    "index must be.",
                    field="reflections",
                ) from error
        if indices[0] + indices[1] + indices[2] != 0:
            raise InvalidInputError(
                f"Line {line}: Miller-Bravais indices must satisfy h + k + i = 0; "
                f"{indices[0]} + {indices[1]} + {indices[2]} = "
                f"{indices[0] + indices[1] + indices[2]}.",
                field="reflections",
                hint="The third index is not free: i = -(h + k).",
            )
        intensity = _number(tokens[4], line=line, field="reflections", what="an intensity")
        random_intensity = (
            _number(tokens[5], line=line, field="reflections", what="a random intensity")
            if len(tokens) == 6
            else 1.0
        )
        if intensity < 0.0:
            raise InvalidInputError(
                f"Line {line}: an integrated intensity cannot be negative.",
                field="reflections",
                hint="A peak that was not observed is 0, not a negative number.",
            )
        if random_intensity <= 0.0:
            raise InvalidInputError(
                f"Line {line}: the random-powder intensity must be strictly positive.",
                field="reflections",
                hint="It divides the measured intensity, so it cannot be zero.",
            )
        plane = CrystalPlane.from_miller_bravais(tuple(indices), phase=phase)
        reflections.append(
            DiffractogramReflection(
                plane=plane, intensity=intensity, random_intensity=random_intensity
            )
        )
    if len(reflections) < 2:
        raise InvalidInputError(
            "The diffractogram route needs at least two reflections at different basal tilts.",
            field="reflections",
            hint=(
                "One peak fixes the pole density at one tilt and says nothing about the rest of "
                "the distribution. Include reflections spanning the range: (0002) at 0 degrees "
                "through (10-10) at 90."
            ),
        )
    return reflections


def _parse_tilt_profile(text: str) -> tuple[np.ndarray, np.ndarray]:
    """Parse ``tilt intensity`` rows, insisting on the equal spacing the quadrature assumes."""

    polar: list[float] = []
    intensity: list[float] = []
    for line, tokens in _data_lines(text, field="profile"):
        if len(tokens) != 2:
            raise InvalidInputError(
                f"Line {line} has {len(tokens)} values; a profile point needs 2.",
                field="profile",
                hint="One tilt angle and one density per line: `25  2.799`.",
            )
        angle = _number(tokens[0], line=line, field="profile", what="a tilt angle")
        if not 0.0 <= angle <= 90.0:
            raise InvalidInputError(
                f"Line {line}: a tilt from the reference direction lies in [0, 90]; got {angle}.",
                field="profile",
            )
        value = _number(tokens[1], line=line, field="profile", what="a pole density")
        if value < 0.0:
            raise InvalidInputError(
                f"Line {line}: a pole density cannot be negative.", field="profile"
            )
        polar.append(angle)
        intensity.append(value)
    if len(polar) < 3:
        raise InvalidInputError(
            "A tilt profile needs at least three points to integrate.",
            field="profile",
            hint="Kearns used nine: the midpoints of 10 degree bins, 5 through 85.",
        )
    angles = np.asarray(polar, dtype=float)
    order = np.argsort(angles)
    angles = angles[order]
    values = np.asarray(intensity, dtype=float)[order]
    steps = np.diff(angles)
    if not np.allclose(steps, steps[0], atol=1e-6):
        raise InvalidInputError(
            "The tilt nodes must be equally spaced; the common bin width is what cancels "
            "out of Kearns' quadrature.",
            field="profile",
            hint=(
                "Use bin midpoints at a constant spacing — 5, 15, 25 ... 85 for 10 degree bins. "
                "Interpolate an unevenly sampled curve onto such a grid first."
            ),
        )
    return angles, values


def _triad_rows(report: Any) -> tuple[tuple[Column, ...], list[dict[str, Any]]]:
    """The per-direction table every route returns, in one shape."""

    columns: tuple[Column, ...] = (
        Column("direction", "Direction", help_text="The specimen direction f is resolved along."),
        Column(
            "f",
            "f",
            numeric=True,
            digits=4,
            help_text="The Kearns parameter: the effective fraction of basal poles along it.",
        ),
        Column(
            "vs_random",
            "f / (1/3)",
            numeric=True,
            digits=3,
            help_text="Against the untextured value of 1/3. Above 1 means poles concentrate here.",
        ),
        Column(
            "mean_angle_deg",
            "Equivalent tilt",
            units="°",
            numeric=True,
            digits=2,
            help_text=(
                "arccos(sqrt(f)): the single basal-pole tilt that would give this f. A summary "
                "of the number, not a measured angle."
            ),
        ),
    )
    rows = [
        {
            "direction": label,
            "f": float(value),
            "vs_random": float(value) / _ISOTROPIC,
            "mean_angle_deg": math.degrees(math.acos(min(1.0, math.sqrt(max(float(value), 0.0))))),
        }
        for label, value in zip(report.direction_labels, report.values, strict=True)
    ]
    return columns, rows


def _report_payload(report: Any, *, spec: PhaseSpec) -> dict[str, Any]:
    """The wire form of a `KearnsReport`, plus what the panel draws.

    Built on the report's own ``to_json`` rather than beside it, so the figure
    and the export cannot describe different numbers. The report's own keys are
    left exactly as it wrote them — in particular ``phase`` stays the plain name
    the JSON contract documents, and the application's fuller specification is
    added beside it as ``phase_spec`` rather than shadowing it.
    """

    payload: dict[str, Any] = dict(report.to_json())
    payload["phase_spec"] = spec.to_json()
    payload["triad_sum"] = report.triad_sum
    payload["is_orthonormal_triad"] = bool(report.is_orthonormal_triad)
    tensor = report.orientation_tensor
    payload["orientation_tensor"] = (
        None if tensor is None else [[float(value) for value in row] for row in np.asarray(tensor)]
    )
    principal = report.principal_values
    payload["principal_values"] = (
        None if principal is None else [float(value) for value in np.asarray(principal)]
    )
    payload["describe"] = report.describe()
    return payload


def _triad_sentence(report: Any) -> str:
    """The closure check, stated the way it should be read."""

    total = report.triad_sum
    if total is None:
        return (
            "The directions are not an orthonormal triad, so the sum rule does not apply and no "
            "closure check is available."
        )
    departure = abs(total - 1.0)
    if departure <= 5e-4:
        return (
            f"The triad sums to {total:.4f}. It is identically 1 for any texture, so this closes "
            "and the result carries no detectable systematic error of that kind."
        )
    return (
        f"The triad sums to {total:.4f}, which departs from 1 by {departure:.4f}. That departure "
        "measures the systematic error of the measurement — an unmeasured tilt range, a wrong "
        "random standard, an unbalanced background — and nothing about the material."
    )


