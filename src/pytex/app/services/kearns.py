def _from_orientations(request: dict[str, Any]) -> dict[str, Any]:
    from pytex.texture.kearns import kearns_from_orientations

    spec, phase = phase_from_request(request["phase"])
    pole = _basal_pole(phase)
    pasted = str(request["euler_angles"] or "").strip()
    if pasted:
        orientations = _parse_euler_angles(pasted, phase=phase)
        source = f"{len(orientations)} pasted orientations"
        model_inputs: dict[str, Any] = {"source": "pasted"}
    else:
        axis_key = str(request["fibre_axis"])
        spread = float(request["spread_deg"])
        count = int(request["count"])
        seed = int(request["seed"])
        orientations = _model_orientations(
            phase=phase, axis_key=axis_key, spread_deg=spread, count=count, seed=seed
        )
        source = f"a model basal fibre {spread:g}° about {axis_key}, {count} orientations"
        model_inputs = {
            "source": "model",
            "fibre_axis": axis_key,
            "spread_deg": spread,
            "count": count,
            "seed": seed,
        }

    report = kearns_from_orientations(
        orientations,
        pole=pole,
        include_symmetry_family=bool(request["include_symmetry_family"]),
    )
    columns, rows = _triad_rows(report)
    strongest = max(rows, key=lambda row: row["f"])
    result = AppResult(
        title=f"Kearns parameters of {spec.name} from {source}",
        summary=(
            f"f_RD = {rows[0]['f']:.4f}, f_TD = {rows[1]['f']:.4f}, f_ND = {rows[2]['f']:.4f}, "
            f"resolved from the (0002) pole of {len(orientations)} orientations. The largest is "
            f"f_{strongest['direction']} = {strongest['f']:.4f}, "
            f"{strongest['vs_random']:.2f} times the untextured value of 1/3. "
            + _triad_sentence(report)
            + " This route evaluates the definition directly, so it carries no binning, "
            "truncation, or normalisation error for the other routes to be compared against."
        ),
        table=ResultTable(
            columns=columns,
            rows=tuple(rows),
            caption="The Kearns parameter along each specimen direction.",
        ),
        data=_report_payload(report, spec=spec),
        inputs=dict(
            model_inputs,
            phase=spec.to_json(),
            include_symmetry_family=bool(request["include_symmetry_family"]),
        ),
        notes=(
            "f is a mean of cos^2, so it lies in [0, 1] and equals 1/3 for a random aggregate. "
            "It is not a volume fraction of any set of grains.",
            "The parameter summarises the texture only for properties of the Kearns form "
            "P = P_par cos^2 phi + P_perp sin^2 phi — second-rank properties such as thermal "
            "expansion and irradiation growth. It says nothing about properties of other "
            "tensor rank.",
        ),
        citations=(_CITATION_KEARNS, _CITATION_MANI, _CITATION_HOLT),
    )
    return result.to_json()


