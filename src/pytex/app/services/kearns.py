@REGISTRY.operation(
    "kearns.from_tilt_profile",
    title="Kearns f from a tilt profile",
    summary="Integrate an azimuthally averaged basal-pole density over tilt — Kearns' Eq. (5).",
    help_text=(
        "The innermost calculation of the whole method, exposed on its own. Kearns showed that "
        "f needs only the pole density averaged over the full 360 degrees of azimuth, `I(phi)`, "
        "as a function of tilt `phi` from the reference direction. The azimuthal detail of a "
        "pole figure is irrelevant to a second-rank property, so a whole figure collapses to "
        "one curve with no loss for this purpose.\n\n"
        "**Use it** when the tilt profile is what you have: a pole-figure ring average, a "
        "published `I(phi)` curve, or the profile the diffractogram route prints. It is also "
        "the way to reproduce a literature calculation, since it is exactly the tabulated "
        "procedure of Kearns' Table 3.\n\n"
        "**Why high tilt matters more than it looks.** The `sin phi` factor converts pole "
        "density to volume fraction: the ring of orientations at tilt `phi` has circumference "
        "proportional to `sin phi`. So the profile at 75 degrees carries real weight even where "
        "the density is small, and the volume fraction vanishes at `phi = 0` however intense "
        "the pole is there.\n\n"
        "**The nodes must be equally spaced.** Samples are treated as bin representatives, as in "
        "Kearns' Table 3, so the common bin width cancels from the quotient. Bin midpoints — 5, "
        "15, ... 85 for 10 degree bins — are the classical choice and avoid the endpoints, where "
        "the integrand vanishes or the measurement is worst.\n\n"
        "**The scale does not matter.** f is a quotient of two integrals of `I`, so times-random, "
        "counts, or anything proportional to density all give the same answer."
    ),
    parameters=(
        phase_parameter(
            label="Phase",
            help_text="The hexagonal phase whose basal pole the profile describes.",
            builtin="zr_hcp",
        ),
        TextParameter(
            name="profile",
            label="Tilt profile",
            help_text=(
                "One point per line: the tilt from the reference direction in degrees, then the "
                "azimuthally averaged pole density in any units proportional to density — "
                "`25  2.799`. The nodes must be equally spaced. Text after `#` is a comment."
            ),
            multiline=True,
            default=_DEFAULT_TILT_PROFILE,
        ),
        ChoiceParameter(
            name="direction",
            label="Reference direction",
            help_text="The specimen direction the tilt is measured from, and that f refers to.",
            options=_DIRECTION_OPTIONS,
            default="ND",
        ),
    ),
    returns=(
        "One row per profile node with its volume-fraction weight and cos^2 contribution, plus "
        "f along the reference direction."
    ),
    panel="kearns",
    citations=(_CITATION_KEARNS, _CITATION_BARON),
    tags=("kearns", "tilt profile", "quadrature", "basal", "texture", "zirconium"),
)
def _from_tilt_profile(request: dict[str, Any]) -> dict[str, Any]:
    from pytex.texture.kearns import kearns_from_tilt_profile

    spec, phase = phase_from_request(request["phase"])
    pole = _basal_pole(phase)
    polar_deg, intensity = _parse_tilt_profile(str(request["profile"]))
    direction_label = str(request["direction"])

    report = kearns_from_tilt_profile(
        polar_deg,
        intensity,
        pole=pole,
        specimen_frame=_specimen_frame(),
        direction=_DIRECTION_VECTORS[direction_label],
        direction_label=direction_label,
    )

    # The same quadrature the function integrates, reported per node so the
    # user can see where f came from rather than only what it was.
    radians = np.deg2rad(polar_deg)
    volume_weight = intensity * np.sin(radians)
    total = float(volume_weight.sum())
    fractions = volume_weight / total if total > 0.0 else np.zeros_like(volume_weight)

    columns: tuple[Column, ...] = (
        Column("polar_deg", "Tilt", units="°", numeric=True, digits=1),
        Column("intensity", "Pole density", numeric=True, digits=4),
        Column(
            "volume_fraction",
            "Volume fraction",
            numeric=True,
            digits=5,
            help_text="I sin(phi), normalised: the fraction of crystals at this tilt.",
        ),
        Column(
            "cos2",
            "cos²φ",
            numeric=True,
            digits=5,
            help_text="What this tilt contributes per unit volume fraction.",
        ),
        Column(
            "contribution",
            "Contribution to f",
            numeric=True,
            digits=5,
            help_text="Volume fraction times cos²φ. These sum to f.",
        ),
    )
    cos2 = np.cos(radians) ** 2
    rows: list[dict[str, Any]] = [
        {
            "polar_deg": float(polar_deg[index]),
            "intensity": float(intensity[index]),
            "volume_fraction": float(fractions[index]),
            "cos2": float(cos2[index]),
            "contribution": float(fractions[index] * cos2[index]),
        }
        for index in range(polar_deg.size)
    ]
    dominant = max(rows, key=lambda row: row["contribution"])
    value = report.value(direction_label)
    payload = _report_payload(report, spec=spec)
    payload["profile"] = {
        "polar_deg": [float(item) for item in polar_deg],
        "intensity": [float(item) for item in intensity],
        "notes": [],
    }
    payload["quadrature"] = rows

    result = AppResult(
        title=f"Kearns f_{direction_label} of {spec.name} from a tilt profile",
        summary=(
            f"f_{direction_label} = {value:.4f} from {polar_deg.size} nodes spanning "
            f"{polar_deg[0]:.0f}° to {polar_deg[-1]:.0f}° in steps of "
            f"{polar_deg[1] - polar_deg[0]:.0f}°, {value / _ISOTROPIC:.2f} times the untextured "
            f"value of 1/3. The largest single contribution comes from the "
            f"{dominant['polar_deg']:.0f}° node, which holds "
            f"{dominant['volume_fraction'] * 100:.1f}% of the volume at cos²φ = "
            f"{dominant['cos2']:.3f}. The contributions in the table sum to f, so the row that "
            "dominates it is visible rather than inferred."
        ),
        table=ResultTable(
            columns=columns,
            rows=tuple(rows),
            caption="Kearns' quadrature, node by node.",
        ),
        data=payload,
        inputs={
            "phase": spec.to_json(),
            "direction": direction_label,
            "node_count": int(polar_deg.size),
            "step_deg": float(polar_deg[1] - polar_deg[0]),
        },
        notes=(
            *report.notes,
            "The volume fraction, not the pole density, is what f averages. A profile that "
            "peaks at zero tilt still contributes nothing there, because the ring of "
            "orientations at zero tilt has no circumference.",
        ),
        citations=(_CITATION_KEARNS, _CITATION_BARON),
    )
    return result.to_json()


