        "reflection's known tilt to `[0001]`. The intensities are an inverse pole figure of the "
        "section normal.\n\n"
        "**Give the random-powder intensity.** Raw peak heights are not pole densities: "
        "reflections differ by orders of magnitude in structure factor and multiplicity. Measure "
        "a powder standard under identical conditions, or calculate the intensities from the "
        "structure. Only ratios enter f, so arbitrary units are fine — but a missing standard "
        "is not a small error, it is the whole normalisation.\n\n"
        "**Span the tilt range.** The `sin phi` factor in Kearns' integral makes the high-tilt "
        "reflections matter far more than their intensity suggests. `(10-10)` at 90 degrees and "
        "`(10-13)` at 31.5 degrees carry weight that `(0002)` does not; omitting the high-tilt "
        "peaks biases f upward.\n\n"
        "**One section gives one number.** This route measures f along the section normal only. "
        "The full triad needs all three principal sections, which for thin product forms means "
        "stacking slices — and the three will not sum to 1 without care, which is exactly the "
        "diagnostic to watch.\n\n"
