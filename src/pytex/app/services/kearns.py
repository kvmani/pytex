"""The Kearns parameter: one number for the basal texture, by every route.

What it does
    Computes the Kearns orientation parameter ``f`` — the effective fraction of
    basal poles aligned with a specimen direction — by the routes the zirconium
    literature actually uses: from discrete orientations, from a theta-2theta
    diffractogram, and from a basal-pole tilt profile. Every route reports the
    same object, so three independent measurements of one specimen can be put
    beside each other and compared.

Why the routes are separate operations rather than one with a mode switch
    They take genuinely different data and carry genuinely different systematic
    errors. A diffractogram needs a random-powder reference and gives one
    direction per section; an orientation set needs none and gives the whole
    triad at once. Hiding that behind a single form would suggest the inputs are
    interchangeable, which is the mistake this panel exists to prevent.

The check that matters more than the number
    For any orthonormal specimen triad, ``f_RD + f_TD + f_ND = 1`` exactly, for
    every texture — it is the trace of a second-moment tensor of unit vectors,
    not an empirical regularity. So a triad that does not sum to 1 measures the
    systematic error of the *measurement*: an unmeasured tilt range, a wrong
    random standard, an unbalanced background. The panel shows the sum wherever
    it applies and says what a departure means, because a Kearns parameter
    quoted without it is a number nobody can check.

The defaults are synthetic, and say so
    The default inputs are the diffraction peaks and tilt profile of a **known**
    basal fibre texture, generated by the recipe in
    ``tests/unit/test_kearns_parameter.py``. That is deliberate and follows the
    texture panel's own principle: the answer is known before the calculation
    runs, so pressing the button without touching a control demonstrates the
    method against a truth rather than against an opinion. All three routes
    return the same ``f_ND`` on those defaults, which is the point.

See ``docs/site/theory/kearns_parameter_and_basal_pole_texture.md`` for the
derivation and the literature.
"""

