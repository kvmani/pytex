def _model_orientations(
    *, phase: Any, axis_key: str, spread_deg: float, count: int, seed: int
) -> Any:
    """A basal fibre texture: c axes clustered about one specimen axis.

    The tilt angles are drawn from a density proportional to
    ``exp(-phi^2 / 2 sigma^2) sin(phi)``, so ``spread_deg`` is the halfwidth of
    the *pole density on the sphere*. Drawing the tilt from the Gaussian
    directly would give a pole density diverging as ``1 / sin(phi)`` at the
    fibre axis — a singular texture no diffraction route could be fairly judged
    against, and the mistake this sampler exists to avoid.
    """

    from pytex.core.orientation import OrientationSet

    generator = np.random.default_rng(seed)
    axis = np.asarray(_DIRECTION_VECTORS[axis_key], dtype=float)
    grid = np.linspace(0.0, np.pi / 2.0, 4001)
    density = np.exp(-0.5 * (grid / np.deg2rad(spread_deg)) ** 2) * np.sin(grid)
    cumulative = np.cumsum(density)
    cumulative /= cumulative[-1]
    tilt = np.interp(generator.uniform(size=count), cumulative, grid)
    azimuth = generator.uniform(0.0, 2.0 * np.pi, size=count)

    helper = np.array([1.0, 0.0, 0.0]) if abs(axis[0]) < 0.9 else np.array([0.0, 1.0, 0.0])
    first = np.cross(helper, axis)
    first /= np.linalg.norm(first)
    second = np.cross(axis, first)
    c_axes = np.cos(tilt)[:, None] * axis + np.sin(tilt)[:, None] * (
        np.cos(azimuth)[:, None] * first + np.sin(azimuth)[:, None] * second
    )
    # The remaining freedom, rotation about c, is randomized: that is what makes
    # this a basal *fibre* rather than a single component.
    spin = generator.uniform(0.0, 2.0 * np.pi, size=count)
    in_plane = np.tile(np.array([1.0, 0.0, 0.0]), (count, 1))
    in_plane[np.abs(c_axes @ np.array([1.0, 0.0, 0.0])) > 0.9] = np.array([0.0, 1.0, 0.0])
    x_axis = np.cross(in_plane, c_axes)
    x_axis /= np.linalg.norm(x_axis, axis=1, keepdims=True)
    y_axis = np.cross(c_axes, x_axis)
    rotated_x = x_axis * np.cos(spin)[:, None] + y_axis * np.sin(spin)[:, None]
    rotated_y = np.cross(c_axes, rotated_x)
    matrices = np.stack([rotated_x, rotated_y, c_axes], axis=2)
    return OrientationSet.from_matrices(
        matrices,
        crystal_frame=phase.crystal_frame,
        specimen_frame=_specimen_frame(),
        phase=phase,
        symmetry=phase.symmetry,
    )


def _parse_euler_angles(text: str, *, phase: Any) -> Any:
    """Parse pasted Bunge Euler triples into an `OrientationSet`."""

    from pytex.core.orientation import OrientationSet

    angles: list[list[float]] = []
    for line, tokens in _data_lines(text, field="euler_angles"):
        if len(tokens) != 3:
            raise InvalidInputError(
                f"Line {line} has {len(tokens)} values; a Bunge orientation needs 3.",
                field="euler_angles",
                hint="phi1, Phi, phi2 in degrees, one orientation per line: `35 20 45`.",
            )
        angles.append(
            [_number(token, line=line, field="euler_angles", what="an angle") for token in tokens]
        )
    return OrientationSet.from_euler_angles(
        np.asarray(angles, dtype=float),
        specimen_frame=_specimen_frame(),
        crystal_frame=phase.crystal_frame,
        symmetry=phase.symmetry,
        phase=phase,
    )


