def _from_diffractogram(request: dict[str, Any]) -> dict[str, Any]:
    from pytex.texture.kearns import (
        basal_tilt_profile,
        harris_texture_coefficients,
        kearns_from_diffractogram,
    )

    spec, phase = phase_from_request(request["phase"])
    _basal_pole(phase)
    reflections = _parse_reflections(str(request["reflections"]), phase=phase)
    normalization = str(request["normalization"])
    bin_width = float(request["bin_width_deg"])
    direction_label = str(request["direction"])

    report = kearns_from_diffractogram(
        reflections,
        specimen_frame=_specimen_frame(),
        normalization=normalization,
        bin_width_deg=bin_width,
        direction=_DIRECTION_VECTORS[direction_label],
        direction_label=direction_label,
    )
    polar_deg, profile, profile_notes = basal_tilt_profile(
        reflections, normalization=normalization, bin_width_deg=bin_width
    )
    harris = harris_texture_coefficients([item.intensity for item in reflections])

    columns: tuple[Column, ...] = (
        Column("plane", "Reflection", help_text="The reflecting plane, in Miller-Bravais form."),
        Column(
            "basal_tilt_deg",
            "Tilt to [0001]",
            units="°",
            numeric=True,
            digits=2,
            help_text="Angle between this plane's normal and the c axis, from the phase metric.",
        ),
        Column("intensity", "Measured I", numeric=True, digits=4),
        Column("random_intensity", "Random I", numeric=True, digits=4),
        Column(
            "density",
            "Pole density",
            numeric=True,
            digits=4,
            help_text="Measured over random: the basal-pole density at this reflection's tilt.",
        ),
        Column(
            "harris",
            "Harris coefficient",
            numeric=True,
            digits=4,
            help_text="The same intensities normalised so the mean coefficient is 1.",
        ),
    )
